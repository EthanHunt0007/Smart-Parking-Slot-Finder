def get_goals(grid):
    goals = set()

    for r in range(len(grid)):
        for c in range(len(grid[0])):
            if grid[r][c] == 'P':
                goals.add((r, c))

    return goals


GOALS = get_goals(GRID)


def get_neighbors(position, grid=None):
    if grid is None:
        grid = GRID

    row, col = position

    directions = [
        (-1, 0),
        (1, 0),
        (0, -1),
        (0, 1)
    ]

    neighbors = []

    for dr, dc in directions:
        nr = row + dr
        nc = col + dc

        if 0 <= nr < len(grid) and 0 <= nc < len(grid[0]):

            if grid[nr][nc] not in ['#', 'X']:
                neighbors.append((nr, nc))

    return neighbors
